export function equipmentBounds(points: readonly (readonly number[])[]) {
  const x = Math.min(...points.map((p) => p[0])),
    y = Math.min(...points.map((p) => p[1]));
  return {
    x,
    y,
    w: Math.max(...points.map((p) => p[0])) - x,
    h: Math.max(...points.map((p) => p[1])) - y,
  };
}
